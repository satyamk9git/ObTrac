"""
Runs real RAGAS evaluation (via the configured Claude Sonnet 5 judge) on every
trace generated by generate_eval_sessions.py. Matches traces to their known
ground_truth (from session_log.json, same order as trace creation within each
session) so ground-truth-dependent metrics run wherever we deliberately
supplied one — including the intentionally WRONG ground_truth case.
Skips the forced-error trace (nothing meaningful to score).
"""
import json
import os
import time
import requests

BACKEND = "http://localhost:8100"

with open(os.path.join(os.path.dirname(__file__), "session_log.json")) as f:
    log = json.load(f)

sql_resp = requests.post(f"{BACKEND}/api/v1/sql/execute", json={
    "query": "SELECT trace_id, session_id, status, created_at FROM traces WHERE project='langgraph-agent' ORDER BY created_at ASC",
})
rows = sql_resp.json()["rows"]

by_session = {}
for row in rows:
    by_session.setdefault(row["session_id"], []).append(row)

# Group log entries by session, in original order (matches trace creation order)
log_by_session = {}
for entry in log:
    log_by_session.setdefault(entry["session"], []).append(entry)

pairs = []  # (trace_id, log_entry)
for sid, log_entries in log_by_session.items():
    trace_rows = by_session.get(sid, [])
    if len(trace_rows) != len(log_entries):
        print(f"WARN: session {sid} has {len(trace_rows)} traces but {len(log_entries)} log entries — matching by position anyway")
    for trace_row, entry in zip(trace_rows, log_entries):
        pairs.append((trace_row["trace_id"], trace_row["status"], entry))

print(f"{len(pairs)} traces to evaluate\n")

results = []
for i, (trace_id, status, entry) in enumerate(pairs):
    if status == "error" or entry["note"].startswith("error"):
        print(f"[{i+1}/{len(pairs)}] SKIP {trace_id[:8]} (error trace, nothing to score)")
        continue

    metrics = ["faithfulness", "answer_relevancy"]
    gt = entry.get("ground_truth")
    if gt:
        metrics += ["context_precision", "context_recall", "answer_correctness"]

    print(f"[{i+1}/{len(pairs)}] {trace_id[:8]} | {entry['note'][:50]:50s} | metrics={metrics}")

    try:
        resp = requests.post(
            f"{BACKEND}/api/v1/evaluation/run",
            json={"trace_id": trace_id, "metrics": metrics, "ground_truth": gt},
            timeout=180,
        )
        data = resp.json()
    except Exception as e:
        data = {"status": "error", "error": str(e)}

    scores = data.get("metrics", {})
    print(f"      -> status={data.get('status')} scores={scores}")
    if data.get("error"):
        print(f"      error: {data['error'][:150]}")

    results.append({
        "trace_id": trace_id, "session": entry["session"], "note": entry["note"],
        "question": entry["question"], "ground_truth": gt,
        "eval_status": data.get("status"), "scores": scores,
        "skipped": data.get("skipped", []),
    })
    time.sleep(0.5)

with open(os.path.join(os.path.dirname(__file__), "eval_results.json"), "w") as f:
    json.dump(results, f, indent=2)

print(f"\nDone. {len(results)} traces evaluated. Wrote test_documents/eval_results.json")

# Quick summary: flag the deliberate failure scenarios and their actual scores
print("\n=== Failure-scenario scores ===")
for r in results:
    if any(k in r["note"] for k in ("hallucination_bait", "false_premise", "bad_ground_truth", "out_of_domain")):
        print(f"- [{r['session']}] {r['question'][:60]}")
        print(f"    note: {r['note']}")
        print(f"    scores: {r['scores']}")
